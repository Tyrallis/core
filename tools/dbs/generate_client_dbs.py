"""Writes core/include/wxl/core/client_dbs.def: every client database the client fork declares.

One row per global store of WoW/Source/DB/DBClient/DBClient.cpp, in the order the file declares
them:

    WXL_CLIENT_DB(global, Rec, store, "file", row_size)

global    the store's name, as the fork and statics.def name it (g_spellDB)
Rec       its record type (SpellRec)
store     plain (WowClientDB) or rle (WowClientDB_RLE)
file      what Rec::GetFilename() answers ("DBFilesClient\\\\Spell.dbc")
row_size  Rec::s_rowSize: the bytes of a record in the file, which the client checks at load

Standard library only. --check compares with the file written and fails on a difference.
"""

import argparse
import pathlib
import re
import sys

HEADER = """// SPDX-License-Identifier: MIT
// Copyright (c) 2026 WarcraftXL
//
// The client databases: every global store the client declares, in its order.
//
// GENERATED by core/tools/dbs/generate_client_dbs.py from the client fork's
// WoW/Source/DB/DBClient/DBClient.cpp and WoW/Source/DB/Rec/. Do not edit: re-run the tool after
// pulling upstream and review the diff.
//
//   WXL_CLIENT_DB(global, Rec, store, file, row_size)
//
//   global    the store, as the fork and statics.def name it
//   Rec       its record type
//   store     plain (WowClientDB<Rec>) or rle (WowClientDB_RLE<Rec>)
//   file      the file it loads, as Rec::GetFilename() answers it
//   row_size  the bytes of one record in the file (Rec::s_rowSize), which the client checks at load

#ifndef WXL_CLIENT_DB
#error "define WXL_CLIENT_DB(global, Rec, store, file, row_size) before including client_dbs.def"
#endif

"""

DECLARATION = re.compile(r"^(WowClientDB(?:_RLE)?)<(\w+)>\s+(g_\w+);", re.M)
FILENAME = re.compile(r"GetFilename\(\)\s*\{\s*return\s+(\"[^\"]*\")\s*;", re.S)
ROW_SIZE = re.compile(r"s_rowSize\s*=\s*(\d+)\s*;")


def rows(client: pathlib.Path) -> list:
    source = (client / "WoW/Source/DB/DBClient/DBClient.cpp").read_text(encoding="utf-8", errors="replace")
    records = client / "WoW/Source/DB/Rec"
    out = []
    for match in DECLARATION.finditer(source):
        store, rec, name = match.group(1), match.group(2), match.group(3)
        header = (records / f"{rec}.h").read_text(encoding="utf-8", errors="replace")
        body = (records / f"{rec}.cpp").read_text(encoding="utf-8", errors="replace")
        size = ROW_SIZE.search(header)
        file = FILENAME.search(body)
        if not size or not file:
            raise SystemExit(f"{rec}: no s_rowSize in {rec}.h or no GetFilename in {rec}.cpp")
        out.append((name, rec, "rle" if store.endswith("_RLE") else "plain", file.group(1), int(size.group(1))))
    if not out:
        raise SystemExit("no store found in DBClient.cpp")
    return out


def render(found: list) -> str:
    text = HEADER
    for name, rec, store, file, size in found:
        text += f"WXL_CLIENT_DB({name}, {rec}, {store}, {file}, {size})\n"
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--client", required=True, type=pathlib.Path, help="the client fork's checkout")
    parser.add_argument("--out", required=True, type=pathlib.Path, help="client_dbs.def to write or check")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()

    found = rows(args.client)
    text  = render(found)
    count = len(found)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is not what the fork gives: run generate_client_dbs.py and review the diff",
                  file=sys.stderr)
            return 1
        print(f"{args.out}: {count} stores, as the fork gives them")
        return 0
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: {count} stores")
    return 0


if __name__ == "__main__":
    sys.exit(main())
